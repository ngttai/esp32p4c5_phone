#!/usr/bin/env python3
"""Icons of the card apps (needs Pillow):
  make_icons.py apps-c [preview.png]   -> components/phone_elf_apps/phone_apps_icon.c (the Apps app: a shopping bag with a download arrow)
  make_icons.py chip <hue 0..360> <out.png>   -> a 126 x 126 chip icon for a sample package"""
import colorsys, os, sys
from PIL import Image, ImageDraw

W = 126
SS = 4                     # supersampling for smooth edges
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def rounded_mask(size, radius):
    m = Image.new("L", (size * SS, size * SS), 0)
    ImageDraw.Draw(m).rounded_rectangle((0, 0, size * SS - 1, size * SS - 1), radius * SS, fill=255)
    return m.resize((size, size), Image.LANCZOS)


def store_image():
    """Our own store icon: a white shopping bag with a download arrow on a warm gradient tile."""
    s = W * SS
    k = SS
    top, bot = (255, 176, 96), (232, 88, 36)
    im = Image.new("RGB", (s, s))
    px = im.load()
    for y in range(s):
        for x in range(s):
            t = (y * 0.8 + x * 0.2) / s
            px[x, y] = tuple(int(top[i] + (bot[i] - top[i]) * t) for i in range(3))
    d = ImageDraw.Draw(im, "RGBA")
    # soft shadow under the bag
    d.rounded_rectangle((30 * k, 51 * k, 96 * k, 106 * k), 12 * k, fill=(120, 30, 0, 70))
    # handle: an arch from the top of the bag
    d.arc((45 * k, 26 * k, 81 * k, 70 * k), 180, 360, fill=(255, 255, 255, 250), width=7 * k)
    # body: a bag a little wider at the bottom
    d.polygon([(36 * k, 47 * k), (90 * k, 47 * k), (97 * k, 98 * k), (29 * k, 98 * k)], fill=(255, 255, 255, 250))
    d.rounded_rectangle((29 * k, 86 * k, 97 * k, 100 * k), 7 * k, fill=(255, 255, 255, 250))
    d.rounded_rectangle((36 * k, 44 * k, 90 * k, 54 * k), 4 * k, fill=(255, 255, 255, 250))
    # download arrow cut out of the body, in the tile color
    c = bot
    d.rounded_rectangle((59.5 * k, 58 * k, 66.5 * k, 76 * k), 2.5 * k, fill=(*c, 255))
    d.polygon([(50 * k, 72 * k), (76 * k, 72 * k), (63 * k, 86 * k)], fill=(*c, 255))
    d.rounded_rectangle((50 * k, 89 * k, 76 * k, 93 * k), 2 * k, fill=(*c, 255))
    # a soft shine on the upper part of the tile
    shine = Image.new("L", (s, s), 0)
    sp = shine.load()
    for y in range(s):
        v = max(0.0, 1.0 - y / (s * 0.55)) * 0.16
        for x in range(s):
            sp[x, y] = int(v * 255)
    im = Image.composite(Image.new("RGB", (s, s), (255, 255, 255)), im, shine)
    im = im.resize((W, W), Image.LANCZOS).convert("RGBA")
    im.putalpha(rounded_mask(W, 30))
    return im


def apps_c():
    im = store_image()
    data = im.tobytes()
    out = ["/* Launcher icon of the Apps app (126 x 126 ARGB8888, rounded corners): a shopping bag with a download arrow.",
           " * Generated by tools/make_icons.py, do not edit. */",
           '#include "lvgl.h"', "", "static const uint8_t phone_apps_icon_map[] = {"]
    px = []
    for i in range(0, len(data), 4):
        r, g, b, a = data[i:i + 4]
        px += [b, g, r, a]          # ARGB8888 little-endian = B G R A
    for i in range(0, len(px), 24):
        out.append("    " + ", ".join("0x%02x" % v for v in px[i:i + 24]) + ",")
    out += ["};", "", "const lv_image_dsc_t phone_apps_icon = {",
            "    .header.cf = LV_COLOR_FORMAT_ARGB8888,", "    .header.magic = LV_IMAGE_HEADER_MAGIC,",
            "    .header.w = %d," % W, "    .header.h = %d," % W, "    .data_size = %d," % len(px),
            "    .data = phone_apps_icon_map,", "};", ""]
    open(os.path.join(ROOT, "components/phone_elf_apps/phone_apps_icon.c"), "w").write("\n".join(out))
    print("phone_apps_icon.c", len(px), "bytes of pixels")
    if len(sys.argv) > 2:
        im.save(sys.argv[2])


def chip(hue, path):
    s = W * SS
    top = tuple(int(c * 255) for c in colorsys.hsv_to_rgb(hue / 360, 0.55, 1.0))
    bot = tuple(int(c * 255) for c in colorsys.hsv_to_rgb((hue + 20) / 360, 0.85, 0.62))
    im = Image.new("RGB", (s, s))
    px = im.load()
    for y in range(s):
        for x in range(s):
            t = (y * 0.8 + x * 0.2) / s
            px[x, y] = tuple(int(top[i] + (bot[i] - top[i]) * t) for i in range(3))
    d = ImageDraw.Draw(im, "RGBA")
    c = s / 2
    k = SS
    for i in range(4):
        off = (-19.5 + i * 13) * k
        d.rounded_rectangle((c + off - 3.5 * k, c - 48 * k, c + off + 3.5 * k, c - 32 * k), 2 * k, fill=(255, 255, 255, 245))
        d.rounded_rectangle((c + off - 3.5 * k, c + 32 * k, c + off + 3.5 * k, c + 48 * k), 2 * k, fill=(255, 255, 255, 245))
        d.rounded_rectangle((c - 48 * k, c + off - 3.5 * k, c - 32 * k, c + off + 3.5 * k), 2 * k, fill=(255, 255, 255, 245))
        d.rounded_rectangle((c + 32 * k, c + off - 3.5 * k, c + 48 * k, c + off + 3.5 * k), 2 * k, fill=(255, 255, 255, 245))
    d.rounded_rectangle((c - 29 * k, c - 29 * k, c + 29 * k, c + 29 * k), 9 * k, fill=(255, 255, 255, 245))
    d.rounded_rectangle((c - 15 * k, c - 15 * k, c + 15 * k, c + 15 * k), 5 * k, fill=(*bot, 255))
    im = im.resize((W, W), Image.LANCZOS).convert("RGBA")
    im.putalpha(rounded_mask(W, 30))
    im.save(path)
    print(path)


if sys.argv[1:2] == ["apps-c"]:
    apps_c()
elif sys.argv[1:2] == ["chip"] and len(sys.argv) == 4:
    chip(float(sys.argv[2]), sys.argv[3])
else:
    sys.exit(__doc__)
